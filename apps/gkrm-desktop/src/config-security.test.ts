import { existsSync, readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { spawnSync } from 'node:child_process'

import { describe, expect, it } from 'vitest'

const root = process.cwd()
/**
 * How many commands this application exposes at all.
 *
 * Pinned rather than derived: the point of the number is that widening the surface an untrusted
 * page can reach has to be something somebody typed, not something a list grew into.
 */
const EXPECTED_COMMAND_COUNT = 24
const expectedPermissions = [
  'allow-app-get-info',
  'allow-select-installed-root',
  'allow-select-package-file',
  'allow-session-list-selections',
  'allow-session-release-selection',
  'allow-scan-installed-root',
  'allow-scan-get-summary',
  'allow-scan-list-resources',
  'allow-scan-get-resource-detail',
  'allow-scan-release',
  'allow-update-recovery-overview',
  'allow-update-recovery-retire-terminal',
  'allow-update-recovery-status',
  'allow-update-recovery-list-candidates',
  'allow-update-recovery-execute',
  'allow-update-recovery-release',
  'allow-update-two-way-preview',
  'allow-update-two-way-get-diff',
  'allow-update-two-way-apply',
  'allow-update-two-way-release',
  'allow-update-history-list',
  'allow-update-history-undo',
  'allow-storage-report',
  'allow-storage-release',
]
const expectedCommands = [
  'app_get_info',
  'select_installed_root',
  'select_package_file',
  'session_list_selections',
  'session_release_selection',
  'scan_installed_root',
  'scan_get_summary',
  'scan_list_resources',
  'scan_get_resource_detail',
  'scan_release',
  'update_recovery_overview',
  'update_recovery_retire_terminal',
  'update_recovery_status',
  'update_recovery_list_candidates',
  'update_recovery_execute',
  'update_recovery_release',
  'update_two_way_preview',
  'update_two_way_get_diff',
  'update_two_way_apply',
  'update_two_way_release',
  'update_history_list',
  'update_history_undo',
  'storage_report',
  'storage_release',
]

function readGeneratedAllowEntries(): Array<{ identifier: string; command: string }> {
  const permissionRoot = join(root, 'src-tauri/permissions/autogenerated')
  return readdirSync(permissionRoot).flatMap((name) => {
    const text = readFileSync(join(permissionRoot, name), 'utf8')
    const identifier = text.match(/identifier = "(allow-[^"]+)"/)?.[1]
    const command = text.match(/commands\.allow = \["([^"]+)"\]/)?.[1]
    return identifier && command ? [{ identifier, command }] : []
  })
}

function expectExactCommandSet(commands: string[]): void {
  expect(commands).toHaveLength(EXPECTED_COMMAND_COUNT)
  expect(new Set(commands).size).toBe(EXPECTED_COMMAND_COUNT)
  expect(commands.sort()).toEqual([...expectedCommands].sort())
}

describe('tauri security configuration', () => {
  it('exposes exactly the reviewed command permissions through Task 32E.2A to the main window', () => {
    const capability = JSON.parse(readFileSync(join(root, 'src-tauri/capabilities/main.json'), 'utf8')) as {
      windows: string[]
      permissions: string[]
      remote?: unknown
    }

    expect(capability.windows).toEqual(['main'])
    expect(capability.remote).toBeUndefined()
    expect(capability.permissions.sort()).toEqual([...expectedPermissions].sort())
    expect(capability.permissions.some((permission) => permission.includes('*'))).toBe(false)
    expect(capability.permissions.some((permission) => /^(fs|shell|process|http|opener|updater|deep-link|dialog|clipboard):/.test(permission))).toBe(false)
  })

  it('uses strict local-only tauri configuration', () => {
    const config = JSON.parse(readFileSync(join(root, 'src-tauri/tauri.conf.json'), 'utf8')) as {
      app: {
        windows: Array<{ label: string; dragDropEnabled: boolean; devtools?: boolean; url?: string }>
        security: { csp: string; assetProtocol: { enable: boolean }; capabilities: string[] }
      }
      bundle?: { externalBin?: string[] }
      plugins?: Record<string, unknown>
    }

    expect(config.app.windows).toHaveLength(1)
    expect(config.app.windows[0]).toMatchObject({ label: 'main', dragDropEnabled: false })
    expect(config.app.windows[0]?.devtools).toBe(false)
    expect(config.app.windows[0]?.url).toBeUndefined()
    expect(config.app.security.assetProtocol.enable).toBe(false)
    expect(config.app.security.capabilities).toEqual(['main'])
    expect(config.app.security.csp).toContain("default-src 'self'")
    expect(config.app.security.csp).not.toMatch(/https:|\*|'unsafe-eval'|cdn/i)
    expect(config.bundle?.externalBin ?? []).toEqual([])
    expect(config.plugins ?? {}).toEqual({})
  })

  it('defines the supported Node LTS runtime policy', () => {
    const packageJson = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as {
      engines?: { node?: string; npm?: string }
      scripts?: Record<string, string>
    }
    const nvmrc = readFileSync(join(root, '.nvmrc'), 'utf8').trim()

    expect(existsSync(join(root, '.node-version'))).toBe(false)
    expect(nvmrc).toBe('22.18.0')
    expect(packageJson.engines).toEqual({ node: '>=22.18.0 <23', npm: '>=10 <12' })
    expect(packageJson.scripts?.['check:runtime']).toBe('node scripts/check-runtime.mjs')
    expect(packageJson.scripts?.dev).toContain('npm run check:runtime &&')
    expect(packageJson.scripts?.typecheck).toContain('npm run check:runtime &&')
    expect(packageJson.scripts?.['test:unit']).toContain('npm run check:runtime &&')
    expect(packageJson.scripts?.build).toContain('npm run check:runtime &&')
  })

  it('defines auditable build and no-bundle scripts', () => {
    const packageJson = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as {
      scripts?: Record<string, string>
    }

    expect(packageJson.scripts?.['audit:production']).toBe('npm audit --omit=dev')
    expect(packageJson.scripts?.['audit:full']).toBe('npm audit')
    expect(packageJson.scripts?.['clean:dist']).toBe('node scripts/clean-dist.mjs')
    expect(packageJson.scripts?.build).toContain('npm run clean:dist &&')
    expect(packageJson.scripts?.['audit:dist-network']).toBe('node scripts/audit-dist-network.mjs')
    expect(packageJson.scripts?.['verify:no-bundle-output']).toBe('node scripts/verify-no-bundle-output.mjs')
    expect(packageJson.scripts?.['tauri:build:no-bundle']).toBe(
      'npm run check:runtime && tauri build --no-bundle && npm run verify:no-bundle-output',
    )
  })

  it('keeps generated frontend chunks free of known bundled network helpers', () => {
    const viteConfig = readFileSync(join(root, 'vite.config.ts'), 'utf8')
    const distAudit = readFileSync(join(root, 'scripts/audit-dist-network.mjs'), 'utf8')

    expect(viteConfig).toContain('modulePreload')
    expect(viteConfig).toContain('polyfill: false')
    expect(viteConfig).toContain('pinia.esm-browser.prod.js')
    expect(distAudit).toContain('XMLHttpRequest')
    expect(distAudit).toContain('WebSocket')
    expect(distAudit).toContain('EventSource')
    expect(distAudit).toContain('Generated output contains forbidden browser networking')
  })

  it('generates exactly the reviewed custom command permissions through Task 32E.2A', () => {
    const allowEntries = readGeneratedAllowEntries()

    expect(allowEntries.map((entry) => entry.identifier).sort()).toEqual([...expectedPermissions].sort())
    expect(allowEntries.map((entry) => entry.command).sort()).toEqual([...expectedCommands].sort())
    expect(allowEntries).toHaveLength(EXPECTED_COMMAND_COUNT)
    for (const command of allowEntries.map((entry) => entry.command)) {
      expect(command).not.toMatch(/^(execute|run_action|open_path|read_file|write_file|invoke_core|run_command)$/)
    }
  })

  it('registers exactly the reviewed Tauri commands, once each', () => {
    const source = readFileSync(join(root, 'src-tauri/src/lib.rs'), 'utf8')
    const handler = source.match(/tauri::generate_handler!\[([\s\S]*?)\]/)?.[1]
    expect(handler).toBeDefined()
    const registered = handler?.match(/[a-z][a-z0-9_]*/g) ?? []
    expect(registered).toHaveLength(EXPECTED_COMMAND_COUNT)
    expect(new Set(registered).size).toBe(EXPECTED_COMMAND_COUNT)
    expect(registered.sort()).toEqual([...expectedCommands].sort())
    expect(expectedPermissions).toHaveLength(EXPECTED_COMMAND_COUNT)
  })

  it('keeps every current command authority surface on the exact same set', () => {
    const librarySource = readFileSync(join(root, 'src-tauri/src/lib.rs'), 'utf8')
    const handler = librarySource.match(/tauri::generate_handler!\[([\s\S]*?)\]/)?.[1]
    const registered = handler?.match(/[a-z][a-z0-9_]*/g) ?? []

    const buildSource = readFileSync(join(root, 'src-tauri/build.rs'), 'utf8')
    const declaration = buildSource.match(/\.commands\(&\[([\s\S]*?)\]\)/)?.[1]
    const declared = [...(declaration?.matchAll(/"([a-z][a-z0-9_]*)"/g) ?? [])].map((match) => match[1] ?? '')

    const allowEntries = readGeneratedAllowEntries()
    const generated = allowEntries.map((entry) => entry.command)
    const generatedByPermission = new Map(allowEntries.map((entry) => [entry.identifier, entry.command]))

    const capability = JSON.parse(readFileSync(join(root, 'src-tauri/capabilities/main.json'), 'utf8')) as {
      permissions: string[]
    }
    expect(capability.permissions.some((permission) => permission.includes('*'))).toBe(false)
    const capable = capability.permissions.map((permission) => generatedByPermission.get(permission) ?? '')

    const clientSource = readFileSync(join(root, 'src/services/tauri/client.ts'), 'utf8')
    const commandMap = clientSource.match(/const commands = \{([\s\S]*?)\}\s+as const/)?.[1]
    const transported = [...(commandMap?.matchAll(/:\s*'([a-z][a-z0-9_]*)'/g) ?? [])].map(
      (match) => match[1] ?? '',
    )

    expectExactCommandSet(registered)
    expectExactCommandSet(declared)
    expectExactCommandSet(generated)
    expectExactCommandSet(capable)
    expectExactCommandSet(transported)
  })

  it('decodes every failure the backend can send, and invents none', () => {
    // A code the decoder does not know decodes to "the desktop adapter failed", which hides the
    // failure the operator was told about. Two lists that must agree, checked rather than trusted.
    const source = readFileSync(join(root, 'src-tauri/src/error.rs'), 'utf8')
    const body = source.match(/pub enum DesktopErrorCode \{([\s\S]*?)\n\}/)?.[1]
    expect(body).toBeDefined()
    const backend = [...(body?.matchAll(/^\s{4}([A-Z][A-Za-z0-9]*),$/gm) ?? [])]
      .map((match) => (match[1] ?? '').replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase())
    expect(backend.length).toBeGreaterThan(20)

    const decoders = readFileSync(join(root, 'src/services/tauri/decoders.ts'), 'utf8')
    const declared = decoders.match(/const errorCodes = new Set<DesktopErrorCode>\(\[([\s\S]*?)\]\)/)?.[1]
    expect(declared).toBeDefined()
    const frontend = [...(declared?.matchAll(/'([a-z0-9_]+)'/g) ?? [])].map((match) => match[1] ?? '')

    expect([...frontend].sort()).toEqual([...backend].sort())
  })

  it('keeps package dependencies local and excludes frontend tauri plugins', () => {
    const packageJson = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as {
      dependencies?: Record<string, string>
      devDependencies?: Record<string, string>
    }
    const dependencies = { ...packageJson.dependencies, ...packageJson.devDependencies }
    expect(Object.keys(dependencies)).not.toContain('@tauri-apps/plugin-dialog')
    expect(Object.keys(dependencies)).not.toContain('@tauri-apps/plugin-fs')
    expect(Object.keys(dependencies)).not.toContain('@tauri-apps/plugin-shell')
    expect(Object.keys(dependencies)).not.toContain('@tauri-apps/plugin-http')
    expect(Object.keys(dependencies)).not.toContain('@tauri-apps/plugin-opener')
    for (const version of Object.values(dependencies)) {
      expect(version).not.toMatch(/^(https?:|git\+|file:)/)
    }
  })

  it('keeps vulnerable dev advisory packages out of the locked tree', () => {
    const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8')) as {
      packages?: Record<string, unknown>
    }
    const packageNames = Object.keys(lock.packages ?? {})
    expect(packageNames).not.toContain('node_modules/js-beautify')
    expect(packageNames).not.toContain('node_modules/editorconfig')
    expect(packageNames).not.toContain('node_modules/minimatch')
    expect(packageNames).not.toContain('node_modules/brace-expansion')
  })

  it('has a clean production npm audit', () => {
    const result = spawnSync('npm', ['audit', '--omit=dev', '--json'], {
      cwd: root,
      encoding: 'utf8',
      shell: process.platform === 'win32',
    })
    expect(result.status).toBe(0)
    const audit = JSON.parse(result.stdout) as { metadata?: { vulnerabilities?: { high?: number; critical?: number } } }
    expect(audit.metadata?.vulnerabilities?.high ?? 0).toBe(0)
    expect(audit.metadata?.vulnerabilities?.critical ?? 0).toBe(0)
  }, 30000)

  it('has a clean full npm audit without advisory exceptions', () => {
    const result = spawnSync('npm', ['audit', '--json'], {
      cwd: root,
      encoding: 'utf8',
      shell: process.platform === 'win32',
    })
    expect(result.status).toBe(0)
    const audit = JSON.parse(result.stdout) as { metadata?: { vulnerabilities?: { high?: number; critical?: number } } }
    expect(audit.metadata?.vulnerabilities?.high ?? 0).toBe(0)
    expect(audit.metadata?.vulnerabilities?.critical ?? 0).toBe(0)
  }, 30000)
})
